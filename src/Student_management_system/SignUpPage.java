    // Validate Username availability and move focus to Password
    private void jTextField2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jTextField2ActionPerformed
        String username = jTextField2.getText().trim();
        if (username.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a Username!", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            jTextField2.requestFocus();
            return;
        }

        if (UserStore.userExists(username)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Username already exists, please choose a different username.", "Sign Up Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
            jTextField2.selectAll();
            jTextField2.requestFocus();
            return;
        }

        jPasswordField2.requestFocus();
    }//GEN-LAST:event_jTextField2ActionPerformed


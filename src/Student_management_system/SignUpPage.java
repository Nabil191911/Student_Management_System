    // Perform user account registration
    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String fullName = jTextField1.getText().trim();
        String extraDetail = jTextField4.getText().trim();
        String username = jTextField2.getText().trim();
        String password = new String(jPasswordField2.getPassword()).trim();

        if (username.isEmpty() && !fullName.isEmpty()) {
            username = fullName;
        }

        if (username.isEmpty() || password.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter both username and password! Fields cannot be left blank.", "Sign Up Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (UserStore.userExists(username)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Username already exists, please type a different username.", "Sign Up Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        boolean success = UserStore.registerUser(username, password);
        if (success) {
            javax.swing.JOptionPane.showMessageDialog(this, "Registration successful! Please log in.", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);

            // Redirect user to Login page after successful sign up
            LoginPage login = new LoginPage();
            login.pack();
            login.setLocationRelativeTo(null);
            login.setVisible(true);
            login.toFront();
            login.requestFocus();
            this.dispose();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Failed to register account. Please try again.", "Sign Up Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed


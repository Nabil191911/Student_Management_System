    // Perform user login authentication
    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String username = jTextField1.getText().trim();
        String password = new String(jPasswordField1.getPassword()).trim();

        // Validate fields
        if (username.isEmpty() || password.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "please enter username and password", "Login Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validate credentials
        if (!UserStore.validateUser(username, password)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Invalid Credential, please try again!! ", "Login Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Open dashboard
        Dashboard dashboard = new Dashboard();
        dashboard.setVisible(true);
        this.dispose();
    }//GEN-LAST:event_jButton1ActionPerformed


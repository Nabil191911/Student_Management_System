    // Add Student Button Action: Validates inputs, CGPA format, blank fields, and appends record to students.txt file
    private void jButton11ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton11ActionPerformed
        String id = jTextField1.getText().trim();
        String dept = jTextField2.getText().trim();
        String cgpa = jTextField3.getText().trim();
        String phone = jTextField4.getText().trim();
        String name = jTextField5.getText().trim();
        String sem = jTextField6.getText().trim();
        String email = jTextField7.getText().trim();

        // Validation: Ensure no text field is left blank
        if (id.isEmpty() || name.isEmpty() || dept.isEmpty() || sem.isEmpty() || cgpa.isEmpty() || phone.isEmpty() || email.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Text boxes can not empty!", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validation: CGPA box must contain only numbers or numbers with point (e.g. 3.85)
        if (!cgpa.matches("^\\d+(\\.\\d+)?$")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please write numbers only or decimal number in the CGPA (e.g. 3.85)", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validation: Phone number format (numbers only)
        if (!phone.matches("\\d+")) {
            javax.swing.JOptionPane.showMessageDialog(this, "write numbers only in the Phone Number", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // File Handling: Append new student details to students.txt
        boolean success = StudentManager.addStudent(id, name, dept, sem, cgpa, phone, email);
        if (success) {
            javax.swing.JOptionPane.showMessageDialog(this, "Student Info successfully added!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            clearFields();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Failed to add student info.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton11ActionPerformed


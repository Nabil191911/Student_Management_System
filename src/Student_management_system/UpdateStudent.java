    // Search student records in students.txt file and populate JTable
    private void performSearch(boolean showNotFoundMsg) {
        String query = jTextField1.getText().trim();

        // Validation: Show error message if search field is left blank
        if (showNotFoundMsg && (query.isEmpty() || query.equalsIgnoreCase("Enter Student ID and press enter") || query.equalsIgnoreCase("Enter Student ID or Name and press enter"))) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a Student ID or Name to search! Field cannot be left blank.", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (query.equalsIgnoreCase("Enter Student ID and press enter") || query.equalsIgnoreCase("Enter Student ID or Name and press enter")) {
            query = "";
        }

        // File Handling: Search student records from students.txt file
        java.util.List<StudentManager.Student> list = StudentManager.searchStudents(query);

        // TableModel giving cell editing access for ALL columns when editingAccessGranted is true
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
            new Object[][] {},
            new String[] { "ID", "Name", "Department", "Semester", "CGPA", "Phone", "Email" }
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                // When Edit button is clicked, ALL columns are 100% editable
                return editingAccessGranted;
            }
        };

        for (StudentManager.Student s : list) {
            model.addRow(new Object[] { s.id, s.name, s.dept, s.sem, s.cgpa, s.phone, s.email });
        }
        jTable1.setModel(model);

        // Display pop up if search query yields no results
        if (showNotFoundMsg && !query.isEmpty() && list.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Student not founded!", "Not Found", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }
    }

    // Edit Button Action: Enables cell editing access for ALL columns of table
    private void performEdit() {
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow < 0 && jTable1.getRowCount() > 0) {
            selectedRow = 0;
            jTable1.setRowSelectionInterval(0, 0);
        }

        if (selectedRow < 0 || jTable1.getRowCount() == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please search and select a student from the table to edit!", "Selection Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Grant cell editing access for all columns
        editingAccessGranted = true;
        jTable1.repaint();
        javax.swing.JOptionPane.showMessageDialog(this, "Editing access enabled for all columns! You can now edit table cells directly. Click Update to save changes.", "Edit Access Granted", javax.swing.JOptionPane.INFORMATION_MESSAGE);
    }

    // Update Button Action: Saves edited JTable cell data back to students.txt file
    private void performUpdate() {
        if (jTable1.isEditing() && jTable1.getCellEditor() != null) {
            jTable1.getCellEditor().stopCellEditing();
        }

        int rowCount = jTable1.getRowCount();
        if (rowCount == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "No student record loaded to update. Please search for a student first.", "Selection Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow < 0) {
            selectedRow = 0;
        }

        javax.swing.table.TableModel model = jTable1.getModel();
        String id = model.getValueAt(selectedRow, 0) != null ? model.getValueAt(selectedRow, 0).toString().trim() : "";
        String name = model.getValueAt(selectedRow, 1) != null ? model.getValueAt(selectedRow, 1).toString().trim() : "";
        String dept = model.getValueAt(selectedRow, 2) != null ? model.getValueAt(selectedRow, 2).toString().trim() : "";
        String sem = model.getValueAt(selectedRow, 3) != null ? model.getValueAt(selectedRow, 3).toString().trim() : "";
        String cgpa = model.getValueAt(selectedRow, 4) != null ? model.getValueAt(selectedRow, 4).toString().trim() : "";
        String phone = model.getValueAt(selectedRow, 5) != null ? model.getValueAt(selectedRow, 5).toString().trim() : "";
        String email = model.getValueAt(selectedRow, 6) != null ? model.getValueAt(selectedRow, 6).toString().trim() : "";

        // Validation: Ensure no field is left blank
        if (id.isEmpty() || name.isEmpty() || dept.isEmpty() || sem.isEmpty() || cgpa.isEmpty() || phone.isEmpty() || email.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please fill in all student details! No field can be left blank.", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validation: Ensure CGPA is numeric or decimal
        if (!cgpa.matches("^\\d+(\\.\\d+)?$")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please write numbers only or decimal number in the CGPA (e.g. 3.85)", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // File Handling: Save updated student record to students.txt file
        boolean success = StudentManager.updateStudent(id, name, dept, sem, cgpa, phone, email);
        if (success) {
            editingAccessGranted = false;
            performSearch(false);
            javax.swing.JOptionPane.showMessageDialog(this, "Student Info updated successfully!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Failed to update student info in file.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

    // Delete Button Action: Deletes selected student record from students.txt file
    private void performDelete() {
        if (jTable1.isEditing() && jTable1.getCellEditor() != null) {
            jTable1.getCellEditor().stopCellEditing();
        }

        int selectedRow = jTable1.getSelectedRow();
        String studentId = "";
        String studentName = "";

        if (selectedRow >= 0) {
            studentId = jTable1.getValueAt(selectedRow, 0).toString().trim();
            studentName = jTable1.getValueAt(selectedRow, 1).toString().trim();
        } else if (jTable1.getRowCount() > 0) {
            studentId = jTable1.getValueAt(0, 0).toString().trim();
            studentName = jTable1.getValueAt(0, 1).toString().trim();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Please search and select a student from the table to delete!", "Selection Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Confirm deletion with user
        int choice = javax.swing.JOptionPane.showConfirmDialog(this,
            "Are you sure you want to delete student: " + studentName + " (ID: " + studentId + ")?",
            "Confirm Delete", javax.swing.JOptionPane.YES_NO_OPTION);

        if (choice == javax.swing.JOptionPane.YES_OPTION) {
            // File Handling: Delete student record from students.txt file
            boolean deleted = StudentManager.deleteStudent(studentId);
            if (deleted) {
                javax.swing.JOptionPane.showMessageDialog(this, "Student Info deleted successfully!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                editingAccessGranted = false;
                performSearch(false);
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Failed to delete student info from file.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }


    private void handleSaveData() {
        javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
        fileChooser.setDialogTitle("Save Student Data Copy");
        fileChooser.setSelectedFile(new java.io.File("student_data_backup.txt"));
        int userSelection = fileChooser.showSaveDialog(this);
        if (userSelection == javax.swing.JFileChooser.APPROVE_OPTION) {
            java.io.File fileToSave = fileChooser.getSelectedFile();
            boolean success = StudentManager.saveDataToFile(fileToSave);
            if (success) {
                javax.swing.JOptionPane.showMessageDialog(this, "Student data successfully saved to: " + fileToSave.getName(), "Save Data", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Failed to save student data.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }

    private void handleLoadData() {
        javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
        fileChooser.setDialogTitle("Select Student Data Text File");
        int userSelection = fileChooser.showOpenDialog(this);
        if (userSelection == javax.swing.JFileChooser.APPROVE_OPTION) {
            java.io.File fileToLoad = fileChooser.getSelectedFile();
            boolean success = StudentManager.loadDataFromFile(fileToLoad);
            if (success) {
                javax.swing.JOptionPane.showMessageDialog(this, "Student data successfully loaded from: " + fileToLoad.getName(), "Load Data", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                loadTableData();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Failed to load student data.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }


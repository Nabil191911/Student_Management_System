    // Load student records into editable table
    private void loadTableData() {
        java.util.List<StudentManager.Student> list = StudentManager.getAllStudents();
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
            new Object[][] {},
            new String[] { "ID", "Name", "Department", "Semester", "CGPA", "Phone", "Email" }
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                // All table cells are 100% editable
                return true;
            }
        };
        for (StudentManager.Student s : list) {
            model.addRow(new Object[] { s.id, s.name, s.dept, s.sem, s.cgpa, s.phone, s.email });
        }
        
        // Auto-save edited cell data back to students.txt file
        model.addTableModelListener(e -> {
            int row = e.getFirstRow();
            if (row >= 0 && row < model.getRowCount()) {
                String id = model.getValueAt(row, 0) != null ? model.getValueAt(row, 0).toString().trim() : "";
                String name = model.getValueAt(row, 1) != null ? model.getValueAt(row, 1).toString().trim() : "";
                String dept = model.getValueAt(row, 2) != null ? model.getValueAt(row, 2).toString().trim() : "";
                String sem = model.getValueAt(row, 3) != null ? model.getValueAt(row, 3).toString().trim() : "";
                String cgpa = model.getValueAt(row, 4) != null ? model.getValueAt(row, 4).toString().trim() : "";
                String phone = model.getValueAt(row, 5) != null ? model.getValueAt(row, 5).toString().trim() : "";
                String email = model.getValueAt(row, 6) != null ? model.getValueAt(row, 6).toString().trim() : "";

                if (!id.isEmpty() && !name.isEmpty() && !dept.isEmpty() && !sem.isEmpty() && !cgpa.isEmpty() && !phone.isEmpty() && !email.isEmpty()) {
                    if (cgpa.matches("^\\d+(\\.\\d+)?$")) {
                        StudentManager.updateStudent(id, name, dept, sem, cgpa, phone, email);
                    }
                }
            }
        });

        jTable1.setModel(model);
    }

